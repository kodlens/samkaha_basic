import 'package:esc_pos_utils_plus/esc_pos_utils_plus.dart';
import 'package:intl/intl.dart';
import 'helper.dart';

class XReportReceipt {
  final double totalSales;
  final double totalPayment;
  final double totalQty;
  final double txCount;
  final double avgTicket;
  final double cashSales;
  final double epaymentSales;
  final List<Map<String, dynamic>> methodBreakdown;
  final String? firstTx;
  final String? lastTx;
  final DateTime? from;
  final DateTime? to;
  final String storeName;
  final String? cashierName;

  XReportReceipt({
    required this.totalSales,
    required this.totalPayment,
    required this.totalQty,
    required this.txCount,
    required this.avgTicket,
    this.cashSales = 0.0,
    this.epaymentSales = 0.0,
    this.methodBreakdown = const [],
    this.firstTx,
    this.lastTx,
    this.from,
    this.to,
    this.storeName = 'SamKaha - Basic',
    this.cashierName,
  });

  String _formatTimeOnly(String? isoStr) {
    if (isoStr == null || isoStr.isEmpty) return '--:--';
    try {
      final dt = DateTime.parse(isoStr);
      return DateFormat('hh:mm a').format(dt);
    } catch (_) {
      return isoStr;
    }
  }

  String _rangeLabel() {
    if (from == null || to == null) return 'Today';
    final fromStr = DateFormat('yyyy-MM-dd HH:mm').format(from!);
    final toStr = DateFormat('yyyy-MM-dd HH:mm').format(to!);
    return '$fromStr to $toStr';
  }

  /// Builds ESC/POS 58mm byte stream for Bluetooth thermal receipt printers
  Future<List<int>> buildReceiptBytes() async {
    final profile = await CapabilityProfile.load();
    final generator = Generator(PaperSize.mm58, profile);
    final now = DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now());
    final bytes = <int>[];

    // Store Header
    bytes.addAll(
      generator.text(
        storeName,
        styles: const PosStyles(
          align: PosAlign.center,
          bold: true,
          height: PosTextSize.size1,
          width: PosTextSize.size1,
        ),
      ),
    );
    bytes.addAll(
      generator.text(
        'X REPORT (MID-DAY READING)',
        styles: const PosStyles(align: PosAlign.center, bold: true),
      ),
    );
    bytes.addAll(
      generator.text(
        'Printed: $now',
        styles: const PosStyles(align: PosAlign.center),
      ),
    );
    bytes.addAll(
      generator.text(
        'Date: ${_rangeLabel()}',
        styles: const PosStyles(align: PosAlign.center),
      ),
    );

    if (firstTx != null || lastTx != null) {
      final window = '${_formatTimeOnly(firstTx)} - ${_formatTimeOnly(lastTx)}';
      bytes.addAll(
        generator.text(
          'Active Window: $window',
          styles: const PosStyles(align: PosAlign.center),
        ),
      );
    }

    if (cashierName != null && cashierName!.trim().isNotEmpty) {
      bytes.addAll(
        generator.text(
          'Generated By: ${cashierName!.trim()}',
          styles: const PosStyles(align: PosAlign.center),
        ),
      );
    }
    bytes.addAll(generator.hr(ch: '-'));

    // Financial Metrics
    bytes.addAll(
      generator.row([
        PosColumn(text: 'TOTAL SALES', width: 7, styles: const PosStyles(bold: true)),
        PosColumn(
          text: Helper.formatReceiptCurrency(totalSales),
          width: 5,
          styles: const PosStyles(align: PosAlign.right, bold: true),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'Cash Sales', width: 7),
        PosColumn(
          text: Helper.formatReceiptCurrency(cashSales),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'E-Pay Sales', width: 7),
        PosColumn(
          text: Helper.formatReceiptCurrency(epaymentSales),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'Transactions', width: 7),
        PosColumn(
          text: txCount.toStringAsFixed(0),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'Items Sold', width: 7),
        PosColumn(
          text: totalQty.toStringAsFixed(0),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'Total Payment', width: 7),
        PosColumn(
          text: Helper.formatReceiptCurrency(totalPayment),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    bytes.addAll(
      generator.row([
        PosColumn(text: 'Avg Ticket', width: 7),
        PosColumn(
          text: Helper.formatReceiptCurrency(avgTicket),
          width: 5,
          styles: const PosStyles(align: PosAlign.right),
        ),
      ]),
    );

    // Method Breakdown Section
    if (methodBreakdown.isNotEmpty) {
      bytes.addAll(generator.hr(ch: '-'));
      bytes.addAll(
        generator.text(
          'PAYMENT BREAKDOWN',
          styles: const PosStyles(align: PosAlign.center, bold: true),
        ),
      );
      for (final m in methodBreakdown) {
        final name = (m['method'] ?? 'Other').toString();
        final count = (m['count'] as num?)?.toInt() ?? 0;
        final total = (m['total'] as num?)?.toDouble() ?? 0.0;
        bytes.addAll(
          generator.row([
            PosColumn(text: '$name ($count)', width: 7),
            PosColumn(
              text: Helper.formatReceiptCurrency(total),
              width: 5,
              styles: const PosStyles(align: PosAlign.right),
            ),
          ]),
        );
      }
    }

    bytes.addAll(generator.hr(ch: '-'));
    bytes.addAll(
      generator.text(
        '*** X REPORT ONLY ***',
        styles: const PosStyles(align: PosAlign.center, bold: true),
      ),
    );
    bytes.addAll(
      generator.text(
        'NON-RESETTING REGISTER READING',
        styles: const PosStyles(align: PosAlign.center),
      ),
    );
    bytes.addAll(
      generator.text(
        'Shift Totals Remain Active',
        styles: const PosStyles(align: PosAlign.center),
      ),
    );
    bytes.addAll(generator.feed(2));
    bytes.addAll(generator.cut());

    return bytes;
  }

  /// Builds aligned plain text formatted for on-screen digital slip preview
  String buildReceiptText() {
    final now = DateFormat('yyyy-MM-dd hh:mm a').format(DateTime.now());
    final buf = StringBuffer();

    void center(String text, [int width = 32]) {
      if (text.length >= width) {
        buf.writeln(text);
      } else {
        final pad = ((width - text.length) / 2).floor();
        buf.writeln('${' ' * pad}$text');
      }
    }

    void line([int width = 32]) {
      buf.writeln('-' * width);
    }

    void row(String label, String value, [int width = 32]) {
      final available = width - value.length;
      if (label.length > available) {
        final truncated = label.substring(0, available > 3 ? available - 1 : 1);
        buf.writeln('$truncated $value');
      } else {
        final spaces = width - label.length - value.length;
        buf.writeln('$label${' ' * (spaces > 0 ? spaces : 1)}$value');
      }
    }

    center(storeName.toUpperCase());
    center('X REPORT (MID-DAY READING)');
    center('Printed: $now');
    center('Range: ${_rangeLabel()}');

    if (firstTx != null || lastTx != null) {
      center('Window: ${_formatTimeOnly(firstTx)} - ${_formatTimeOnly(lastTx)}');
    }

    if (cashierName != null && cashierName!.trim().isNotEmpty) {
      center('Cashier: ${cashierName!.trim()}');
    }

    line();
    row('GROSS SALES', Helper.formatNumberWithPeso(totalSales));
    row('Cash Sales', Helper.formatNumberWithPeso(cashSales));
    row('E-Payment Sales', Helper.formatNumberWithPeso(epaymentSales));
    row('Total Payments', Helper.formatNumberWithPeso(totalPayment));
    row('Transactions', txCount.toStringAsFixed(0));
    row('Items Sold', totalQty.toStringAsFixed(0));
    row('Avg Ticket', Helper.formatNumberWithPeso(avgTicket));

    if (methodBreakdown.isNotEmpty) {
      line();
      center('PAYMENT BREAKDOWN');
      for (final m in methodBreakdown) {
        final name = (m['method'] ?? 'Other').toString();
        final count = (m['count'] as num?)?.toInt() ?? 0;
        final total = (m['total'] as num?)?.toDouble() ?? 0.0;
        row('$name ($count)', Helper.formatNumberWithPeso(total));
      }
    }

    line();
    center('*** X REPORT ONLY ***');
    center('NON-RESETTING REGISTER READING');
    center('Shift Totals Remain Active');

    return buf.toString();
  }
}
